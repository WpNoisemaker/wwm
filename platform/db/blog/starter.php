Every Nigerian wedding has the same arithmetic problem. The venue holds a fixed number, the budget feeds a fixed number, and both families arrive with lists that add up to twice that. A guest list is the first real planning decision you make together, so make it early and make it on paper.

## Start with the venue and the budget, not the names

Decide how many people you can seat and feed before anyone writes a single name. Ask the venue for its true seated capacity, then take ten per cent off for vendors, the bridal train and the guests who arrive with somebody nobody invited. That number is your list. Everything after this is sharing it out.

## Split the numbers between the families

The fairest way is usually three parts: the couple, the bride's family and the groom's family. Agree the split out loud, write it down, and let each family fill its own share. When an aunty asks for twenty more seats, the answer is simple: it comes from her side's share.

- Agree the split before the introduction, not after the venue is booked.
- Give each side one person who owns their list.
- Keep a short waiting list for when people say no.

## Decide on plus-ones once, for everybody

"Can I bring someone?" is the question you will hear most. Pick one rule (married and engaged couples only, or nobody brings anyone) and apply it to everyone. The rule protects you; exceptions are where the arguments start.

## Give each ceremony its own guest list

The introduction, the traditional wedding, the nikkah or church service and the reception rarely share one list. On a [wedding page](/templates) each programme carries its own date, venue and dress code, and a programme marked private shows as by invitation only, with the venue hidden. Guests only RSVP for the events they are invited to.

## Track every RSVP in one place

A spreadsheet that four people edit on WhatsApp will be wrong by Thursday. When guests reply on your page they give their name, how many are coming and a note, and you see the running total on your dashboard. On [Pro and above](/pricing) every guest who says yes gets an entry pass with its own code, and you can check people in at the gate.

## Plan for the guests you did not invite

At most Nigerian weddings some uninvited guests will come. Leave a small buffer of seats and food, brief the people at the door, and use the entry passes to see quickly who is on the list and who is not.

## A quick guest list checklist

1. Fix the number from the venue and the budget.
2. Split it between the couple and both families, in writing.
3. Agree one plus-one rule.
4. Give each ceremony its own list.
5. Collect RSVPs on your wedding page and follow up a week before.
6. Keep ten per cent in reserve.

