	<h1 class="prose__h">Privacy</h1>
	<p class="note note--bad"><b>A starting point, not finished legal advice.</b> This describes how the service handles information today. Have a lawyer in your jurisdiction review and complete it before you rely on it.</p>
	<h2>What we hold</h2>
	<p>For couples: the email, name and phone number you give us, and whatever you put on your wedding page. For guests: the name, and optionally the phone or email, left with an RSVP or a note. For everyone: the ordinary server records a website keeps.</p>
	<h2>The anonymous community</h2>
	<p>Posts carry whatever name the poster typed. There is no account behind them, and no real name is attached. We do not publish, and cannot reconstruct, who wrote a given post from what is shown on the page.</p>
	<h2>What we never do</h2>
	<p>We do not sell your information. We do not send marketing on behalf of anybody else. Guest lists belong to the couple, not to us, and are never shared with vendors or sellers.</p>
	<h2>Messages</h2>
	<p>Email is used for the things you ask for — sign-in, resets, receipts, RSVPs. WhatsApp and SMS are switched off entirely until an administrator configures them, so nothing goes to a phone by accident.</p>
	<h2>Payments</h2>
	<p>Card details are handled by the payment provider and never stored here.</p>
	<h2>Your choices</h2>
	<p>You can edit or delete your page and your account at any time. Ask us and we will tell you what we hold about you.</p>
